#!/usr/bin/env python3
"""Emit Gauss-Hermite node/weight table (weight e^{-x^2}) for the deficit
quadrature used by both the C++ PS path and the OpenCL PL kernel."""
import numpy as np, pathlib
N = 48
z, w = np.polynomial.hermite.hermgauss(N)
out = ["#pragma once", "// auto-generated by tools/gen_gh_table.py (do not edit)",
       f"#define GH_N {N}",
       "static const double kGH_Z[GH_N] = {"]
out += [", ".join(f"{v:.17e}" for v in z[i:i+4]) + "," for i in range(0, N, 4)]
out += ["};", "static const double kGH_W[GH_N] = {"]
out += [", ".join(f"{v:.17e}" for v in w[i:i+4]) + "," for i in range(0, N, 4)]
out += ["};"]
pathlib.Path("include/gh_table.h").write_text("\n".join(out) + "\n")
print("wrote include/gh_table.h", N, "nodes")
