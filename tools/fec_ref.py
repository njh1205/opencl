def geom(L, cid, pid):
    width = CRC[cid][2]
    A = L + width
    T = A + K_CONSTRAINT - 1
    ncoded = 2 * T
    return A, T, ncoded, punctured_len(ncoded, pid)


def build_case(L, cid, pid, kind, par, seed, chan, tag, brute=False):
    """One frame, end to end: CRC -> conv -> puncture -> interleave -> channel ->
    deinterleave -> depuncture -> Viterbi. Returns the dict the writer flattens."""
    A, T, ncoded, npunc = geom(L, cid, pid)
    rng = np.random.default_rng(seed)
    info = rng.integers(0, 2, L).astype(np.uint8)
    coded = conv_encode(info, cid)                       # (ncoded,)
    assert len(coded) == ncoded
    punc = puncture(coded, pid)                          # (npunc,)
    perm, par_eff, att = make_interleaver(kind, npunc, par, seed)
    tx = interleave(punc, perm)
    if chan[0] == "llr":
        llr = direct_llr(tx, chan[1], chan[2], rng)[0]
        M, n0, amp = 0, chan[2] ** 2, chan[1]
    else:
        M, n0 = chan[1], chan[2]
        amp = 0.0
        llr = qam_llr(tx[None, :], M, n0, rng)[0]
    assert len(llr) == npunc
    dec, metric, ok = viterbi_frame(llr, L, cid, pid, perm)
    assert len(dec) == L

    bf_metric, bf_info = 0.0, np.zeros(L, np.uint8)
    if brute:
        bf_metric, bf_info = brute_force_ml(llr, L, cid, pid, perm)
        # same tolerance the bench uses: 1e-12 relative. The two summations
        # associate differently (Viterbi per trellis step, enumeration per bit), so
        # a few ulps are expected; measured worst over the shipped brute-forced
        # cases is 5.4e-16 relative.
        if abs(bf_metric - metric) > 1e-12 * max(1.0, abs(bf_metric)):
            raise SystemExit("[fec_ref] %s: Viterbi metric %.12f != brute force %.12f"
                             % (tag, metric, bf_metric))
    return dict(L=L, cid=cid, pid=pid, kind=kind, par_req=par, par_eff=par_eff,
                att=att, M=M, ncoded=ncoded, npunc=npunc, seed=seed, n0=n0, amp=amp,
                info=info, coded=coded, tx=tx, perm=perm, llr=llr, dec=dec,
                metric=metric, crc_ok=1 if ok else 0, has_bf=1 if brute else 0,
                bf_metric=bf_metric, bf_info=bf_info, tag=tag, A=A, T=T)


def cases():
    """Adversarial mix: degenerate metrics, tiny frames, every CRC, every rate,
    both interleavers, direct LLRs and real QAM LLRs, and a frame big enough that
    the file size is a real number."""
    c = []
    # 0: noiseless, no CRC, no puncturing, no interleaving, + brute force.
    c.append(build_case(8, 0, 0, 0, 0, 20261026 + 1, ("llr", 6.0, 0.0),
                        "noiseless hard LLR", brute=True))
    # 1: the fully degenerate metric. Every path scores 0.0, so the answer is
    #    pure tie-break: this is the case that proves the two sides' tie rules are
    #    the same rule, not two rules that happen to agree.
    c.append(build_case(8, 0, 0, 0, 0, 20261026 + 2, ("llr", 0.0, 0.0),
                        "all-zero LLR (tie-break)", brute=True))
    # 2: weak noisy direct LLRs, small enough to enumerate.
    c.append(build_case(8, 0, 0, 0, 0, 20261026 + 3, ("llr", 1.0, 1.2),
                        "noisy LLR sigma=1.2", brute=True))
    # 3: L=10 with a CRC-16 and rate 2/3 -- punctured erasures inside a brute
    #    forced frame, so the erased positions have to be exactly neutral.
    c.append(build_case(10, 2, 1, 0, 0, 20261026 + 4, ("llr", 2.0, 0.8),
                        "CRC-16 rate 2/3 punctured", brute=True))
    # 4: QPSK at 10 dB, tiny frame, brute forced through a real demodulator.
    c.append(build_case(10, 0, 0, 0, 0, 20261026 + 5, ("qam", 4, 0.1),
                        "QPSK n0=0.1", brute=True))
    # 5..7: the three rates through 16-QAM with an S-random interleaver, CRC-16.
    c.append(build_case(96, 2, 0, 2, 8, 20261026 + 6, ("qam", 16, 0.05),
                        "16-QAM rate 1/2 S-random"))
    c.append(build_case(96, 2, 1, 2, 8, 20261026 + 7, ("qam", 16, 0.05),
                        "16-QAM rate 2/3 S-random"))
    c.append(build_case(96, 2, 2, 2, 8, 20261026 + 8, ("qam", 64, 0.05),
                        "64-QAM rate 3/4 S-random"))
    # 8: CRC-24A, row-column interleaver, QPSK, essentially noiseless: a frame
    #    that MUST come back clean, so a nonzero BLER here is a bug not a statistic.
    c.append(build_case(96, 1, 0, 1, 12, 20261026 + 9, ("qam", 4, 0.001),
                        "QPSK CRC-24A row-column"))
    # 9: deep below the decoding threshold -- the decoder must still terminate,
    #    still produce a valid-length answer, and the CRC must (almost certainly)
    #    say the frame is wrong. Gates the failure path, not the success path.
    c.append(build_case(200, 0, 0, 0, 0, 20261026 + 10, ("llr", 0.2, 1.0),
                        "below threshold sigma=1.0"))
    # 10: L=1, the smallest legal payload: A = 17 with CRC-16, so the tail is most
    #    of the trellis and an off-by-one in T shows up here first.
    c.append(build_case(1, 2, 2, 2, 8, 20261026 + 11, ("llr", 4.0, 0.0),
                        "L=1 rate 3/4 noiseless", brute=True))
    # 11: a 512-bit payload with CRC-24A through 64-QAM, the largest frame shipped.
    c.append(build_case(512, 1, 1, 2, 8, 20261026 + 12, ("qam", 64, 0.02),
                        "64-QAM L=512 CRC-24A rate 2/3"))
    return c


def write(cases_, path):
    blob = [struct.pack("<i", len(cases_))]
    for c in cases_:
        blob.append(struct.pack(
            "<11iq4dB", c["L"], c["cid"], c["pid"], c["kind"], c["par_req"],
            c["par_eff"], c["att"], c["M"], c["ncoded"], c["npunc"], c["has_bf"],
            c["seed"], c["n0"], c["amp"], c["metric"], c["bf_metric"], c["crc_ok"]))
        for arr, dtype, count in (
                (c["info"], "<u1", c["L"]), (c["coded"], "<u1", c["ncoded"]),
                (c["tx"], "<u1", c["npunc"]), (c["perm"], "<i4", c["npunc"]),
                (c["llr"], "<f8", c["npunc"]), (c["dec"], "<u1", c["L"]),
                (c["bf_info"], "<u1", c["L"])):
            a = np.ascontiguousarray(arr).astype(dtype)
            assert a.size == count, (a.size, count)
            blob.append(a.tobytes())
    data = b"".join(blob)
    pathlib.Path(path).write_bytes(data)
    return len(data)


def main():
    t0 = time.time()
    selfcheck()
    cs = cases()
    for c in cs:
        print("  case L=%-4d crc=%d rate=%d/%d int=%d(S=%d,%d att) M=%-3d "
              "npunc=%-5d metric=%+11.6f crc_ok=%d bf=%d  %s"
              % (c["L"], c["cid"], *puncture_rate(c["pid"]), c["kind"], c["par_eff"],
                 c["att"], c["M"], c["npunc"], c["metric"], c["crc_ok"], c["has_bf"],
                 c["tag"]))
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "build", "fec_vectors.bin")
    pathlib.Path(os.path.dirname(out)).mkdir(exist_ok=True)
    nb = write(cs, out)
    nbf = sum(1 for c in cs if c["has_bf"])
    print("wrote %s (%d cases, %d of them brute-force cross-checked, %d bytes, "
          "%.1f s)" % (out, len(cs), nbf, nb, time.time() - t0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
