# ---------------------------------------------------------------------------
# GF(2) arithmetic: the CRC as polynomial division, not as a shift register.
# ---------------------------------------------------------------------------
def popcount(a):
    """Bit count of every element of an integer array, WITHOUT np.bitwise_count.

    np.bitwise_count is numpy >= 2.0 only, and this oracle has to run wherever the
    benches run -- the x86/NVIDIA host this repo is also gated on has numpy 1.24.4,
    where the 2.0 spelling is an AttributeError at import-to-use time, i.e. the
    whole FEC gate silently becomes "oracle unavailable". One portable definition
    beats a version branch: the arrays here are 64 states x 2 inputs, so a 64-step
    shift-and-mask costs nothing measurable (the oracle's total runtime is 0.4 s).
    """
    a = np.asarray(a).astype(np.uint64)
    out = np.zeros(a.shape, dtype=np.uint64)
    for b in range(64):
        out += (a >> np.uint64(b)) & np.uint64(1)
    return out


def gf2_mod(a, g):
    """a mod g in GF(2)[x]; ints with the MSB as the highest power."""
    gl = g.bit_length()
    while a.bit_length() >= gl:
        a ^= g << (a.bit_length() - gl)
    return a


def bits_to_int(bits):
    """MSB-first bit array -> integer (np.packbits zero-pads the tail, so shift it
    back out rather than letting the padding become low-order zeros)."""
    b = np.asarray(bits, dtype=np.uint8)
    if b.size == 0:
        return 0
    pad = (-b.size) % 8
    return int.from_bytes(np.packbits(b, bitorder="big").tobytes(), "big") >> pad


def crc_div(bits, poly, width, init=0):
    """CRC by long division: (M(x)*x^width + I*x^|M|) mod g(x).

    The init register folds in as I*x^|M| because the LFSR is linear over GF(2) in
    (init, message): shifting a loaded register through |M| zero input bits is
    multiplication by x^|M|. That identity is what lets one polynomial-division
    routine reproduce both the 3GPP configuration (init = 0) and the two nonzero
    init check values in CRC_CHECK_VALUES.
    """
    g = poly | (1 << width)
    n = len(bits)
    return gf2_mod((bits_to_int(bits) << width) ^ (init << n), g)


def crc_matrix(A, poly, width):
    """(width, A) GF(2) matrix with crc = (M @ mat.T) % 2.

    Column i is x^(width+A-1-i) mod g. Built with the divide-by-x recurrence
    r <- (r >> 1) ^ (((1<<(width-1)) | (poly>>1)) if r & 1 else 0), which is
    O(width) per column instead of O(A); selfcheck() verifies it against gf2_mod
    on every column index it can afford to.
    """
    mat = np.zeros((width, A), np.int8)
    fb = (1 << (width - 1)) | (poly >> 1)
    r = gf2_mod(1 << (width + A - 1), poly | (1 << width))
    for i in range(A):
        for b in range(width):
            mat[b, i] = (r >> (width - 1 - b)) & 1
        r = (r >> 1) ^ (fb if (r & 1) else 0)
    return mat


def crc_bits(v, width):
    """integer -> width bits, MSB (p_0) first."""
    return np.array([(v >> (width - 1 - b)) & 1 for b in range(width)], np.uint8)


def crc_append(msg, cid, mat=None):
    """msg[A] uint8 -> msg || parity, using the matrix form when one is given."""
    msg = np.asarray(msg, np.uint8)
    _, poly, width = CRC[cid]
    if width == 0:
        return msg.copy()
    if mat is None:
        mat = crc_matrix(len(msg), poly, width)
    par = (msg.astype(np.int8) @ mat.T) % 2
    return np.concatenate([msg, par.astype(np.uint8)])


def crc_check(codeword, cid):
    _, poly, width = CRC[cid]
    if width == 0:
        return True
    return crc_div(np.asarray(codeword, np.uint8), poly, width, 0) == 0


# ---------------------------------------------------------------------------
# trellis / encoder, Sionna's state indexing (see sionna.phy.fec.conv.Trellis)
# ---------------------------------------------------------------------------
def trellis(gen=GEN_POLY, K=K_CONSTRAINT):
    """to_nodes[ns,2], out_bits[ns,2,2] built fully vectorised over the states."""
    ns = 1 << (K - 1)
    s = np.arange(ns)
    to = np.empty((ns, 2), np.int32)
    op = np.empty((ns, 2, 2), np.int8)
    for u in (0, 1):
        w = (u << (K - 1)) | s                     # window, MSB = current input
        to[:, u] = (u << (K - 2)) | (s >> 1)
        op[:, u, 0] = popcount(w & gen[0]) & 1
        op[:, u, 1] = popcount(w & gen[1]) & 1
    return to, op


def gen_matrix(A, gen=GEN_POLY, K=K_CONSTRAINT):
    """(T, 2T) GF(2) generator matrix of the zero-tailed code, T = A + K - 1.

    c[2t+j] = XOR_i g_j[i] * u[t-i], i.e. G[t-i, 2t+j] = g_j[i]. Multiplying by
    this is a different computation from walking the shift register, which is the
    point: the C++ does the walk.
    """
    T = A + K - 1
    G = np.zeros((T, 2 * T), np.int8)
    for i in range(K):
        g0 = (gen[0] >> (K - 1 - i)) & 1
        g1 = (gen[1] >> (K - 1 - i)) & 1
        rows = np.arange(0, T - i)
        G[rows, 2 * (rows + i) + 0] = g0
        G[rows, 2 * (rows + i) + 1] = g1
    return G


def conv_encode(info, cid, gen=GEN_POLY, K=K_CONSTRAINT):
    """info[L] -> coded[2*(A+K-1)] with the CRC appended and a zero tail."""
    a = crc_append(info, cid)
    A = len(a)
    u = np.concatenate([a.astype(np.int8), np.zeros(K - 1, np.int8)])
    return ((u @ gen_matrix(A, gen, K)) % 2).astype(np.uint8)


def conv_encode_batch(info, cid, gen=GEN_POLY, K=K_CONSTRAINT):
    """(B, L) -> (B, ncoded); the batched path tools/fec_bler.py runs on."""
    info = np.atleast_2d(np.asarray(info, np.uint8))
    B, L = info.shape
    width = CRC[cid][2]
    A = L + width
    if width:
        mat = crc_matrix(A - width, CRC[cid][1], width)
        par = ((info.astype(np.int8) @ mat.T) % 2).astype(np.uint8)
        a = np.concatenate([info, par], axis=1)
    else:
        a = info
    u = np.concatenate([a.astype(np.int8), np.zeros((B, K - 1), np.int8)], axis=1)
    return ((u @ gen_matrix(A, gen, K)) % 2).astype(np.uint8)


def punctured_len(ncoded, pid):
    pat = PUNCT_PAT[pid]
    full, rem = divmod(ncoded, len(pat))
    return int(full * pat.sum() + pat[:rem].sum())


def puncture_mask(ncoded, pid):
    pat = PUNCT_PAT[pid]
    return np.tile(pat, -(-ncoded // len(pat)))[:ncoded].astype(bool)


def puncture(coded, pid):
    return np.asarray(coded, np.uint8)[puncture_mask(len(coded), pid)]


def depuncture(llr, ncoded, pid):
    """(B, npunc) -> (B, ncoded) with the erased positions written as exactly 0."""
    llr = np.atleast_2d(np.asarray(llr, np.float64))
    out = np.zeros((llr.shape[0], ncoded), np.float64)
    out[:, puncture_mask(ncoded, pid)] = llr
    return out


def puncture_rate(pid):
    """Effective rate counted out of the pattern: period / (2 * ones)."""
    pat = PUNCT_PAT[pid]
    num, den = len(pat), 2 * int(pat.sum())
    g = np.gcd(num, den)
    return num // g, den // g


