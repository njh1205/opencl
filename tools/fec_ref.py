# interleavers
# ---------------------------------------------------------------------------
M64 = (1 << 64) - 1


def splitmix64(state):
    """The same stream ref/fec.cpp runs; Python ints are unbounded, so mask."""
    state = (state + 0x9E3779B97F4A7C15) & M64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return state, z ^ (z >> 31)


def srandom_spread(n, s_req):
    """Effective S; see the measured feasibility table in ref/fec.h."""
    if n < 4:
        return 0
    return max(1, min(s_req, int(np.sqrt(n) / 3.0)))


S_RANDOM_MAX_ATTEMPTS = 200            # must equal kSRandomMaxAttempts in fec.h
S_RANDOM_MAX_DRAWS = 1000              # must equal kSRandomMaxDraws in fec.h


def _s_ok(perm, i, c, S):
    lo = max(0, i - S)
    if lo >= i:
        return True
    # vectorised window test: the same predicate as ref/fec.cpp's s_ok
    return bool(np.all(np.abs(c - perm[lo:i]) > S))


def make_interleaver(kind, n, par, seed):
    """-> (perm[n] int32, effective par, attempts used). Mirrors make_interleaver
    in ref/fec.cpp draw for draw, including the restart ladder."""
    if n <= 0:
        return np.zeros(0, np.int32), par, 0
    if kind == 0:
        return np.arange(n, dtype=np.int32), par, 1
    if kind == 1:
        # Write by rows, read by columns: element [c, r] of the (cols, rows) grid
        # is source index r*cols + c, and ravel() in C order walks c outer / r
        # inner, which IS the column-major readout. Ravelling a (rows, cols) grid
        # instead yields the identity permutation -- that is exactly what the
        # first bench run caught (case 8: 250 of 252 perm entries wrong).
        cols = max(1, min(par if par > 0 else n, n))
        rows = -(-n // cols)
        idx = (np.arange(rows)[None, :] * cols + np.arange(cols)[:, None]).ravel()
        return idx[idx < n].astype(np.int32), cols, 1
    S = srandom_spread(n, par)
    if S == 0:
        return np.arange(n, dtype=np.int32), 0, 1
    perm = np.zeros(n, np.int64)
    for attempt in range(S_RANDOM_MAX_ATTEMPTS):
        st = (seed + attempt) & M64
        used = np.zeros(n, bool)
        complete = True
        for i in range(n):
            chosen = -1
            for _ in range(S_RANDOM_MAX_DRAWS):
                st, v = splitmix64(st)
                c = int(v % n)
                if used[c]:
                    continue
                if _s_ok(perm, i, c, S):
                    chosen = c
                    break
            if chosen < 0:
                complete = False
                break
            perm[i] = chosen
            used[chosen] = True
        if complete:
            return perm.astype(np.int32), S, attempt + 1
    # budget exhausted: deterministic ladder that always completes (draws -> first
    # fitting unused -> smallest unused). The violation count is then nonzero and
    # the bench fails; this branch is not reachable for the shipped lengths.
    st = seed & M64
    used = np.zeros(n, bool)
    for i in range(n):
        chosen = -1
        for _ in range(S_RANDOM_MAX_DRAWS):
            st, v = splitmix64(st)
            c = int(v % n)
            if not used[c] and _s_ok(perm, i, c, S):
                chosen = c
                break
        if chosen < 0:
            free = np.flatnonzero(~used)
            for c in free:
                if _s_ok(perm, i, int(c), S):
                    chosen = int(c)
                    break
        if chosen < 0:
            chosen = int(np.flatnonzero(~used)[0])
        perm[i] = chosen
        used[chosen] = True
    return perm.astype(np.int32), S, S_RANDOM_MAX_ATTEMPTS + 1


def interleave(x, perm):
    return np.asarray(x)[..., perm]


def deinterleave(y, perm):
    out = np.empty_like(np.asarray(y))
    out[..., perm] = y
    return out


def spread_violations(perm, S):
    """Pairs with |i-j| <= S but |perm[i]-perm[j]| <= S (must be 0)."""
    if S < 1 or len(perm) < 2:
        return 0
    p = np.asarray(perm)
    bad = 0
    for d in range(1, min(S, len(p) - 1) + 1):
        bad += int(np.sum(np.abs(p[d:] - p[:-d]) <= S))
    return bad


def min_spread(perm, S):
    if S < 1 or len(perm) < 2:
        return -1
    p = np.asarray(perm)
    return min(int(np.abs(p[d:] - p[:-d]).min())
               for d in range(1, min(S, len(p) - 1) + 1))


# ---------------------------------------------------------------------------
# Viterbi, batched over frames: (B, 2T) depunctured LLRs in, (B, A) bits out.
# ---------------------------------------------------------------------------
def viterbi(llr_dep, gen=GEN_POLY, K=K_CONSTRAINT):
    """llr_dep (B, 2T) -> (info (B, T-K+1) uint8, metric (B,) float64).

    Per trellis step the update is two (B, ns/2) gathers rather than a 64-iteration
    loop: for a next state n the input bit is u = n >> (K-2) and its two
    predecessors are 2q and 2q+1 with q = n & (ns/2 - 1), so both candidates for
    all states and all frames are one fancy-index + one comparison. `take = c1 > c0`
    is strict, which is the slot-0 (smaller predecessor) tie-break ref/fec.h pins.
    """
    llr_dep = np.atleast_2d(np.asarray(llr_dep, np.float64))
    B, n2 = llr_dep.shape
    T = n2 // 2
    A = T - (K - 1)
    if A <= 0:
        return np.zeros((B, 0), np.uint8), np.zeros(B)
    ns = 1 << (K - 1)
    h = ns >> 1
    assert ns <= 256, "survivor memory is uint8; K=7 gives 64 states"
    assert h <= 128
    _, op = trellis(gen, K)
    q = np.arange(h)
    s0, s1 = 2 * q, 2 * q + 1
    # branch-metric coefficients, precomputed once per (state, input): the LLRs are
    # what change per step, the tap parities do not.
    o0 = op[s0, :, :].astype(np.float64)        # (h, 2, 2) indexed [q][u][j]
    o1 = op[s1, :, :].astype(np.float64)
    metric = np.full((B, ns), -np.inf)
    metric[:, 0] = 0.0
    surv = np.zeros((T, B, ns), np.uint8)
    new = np.empty((B, ns))
    for t in range(T):
        l0 = llr_dep[:, 2 * t][:, None]
        l1 = llr_dep[:, 2 * t + 1][:, None]
        for u in (0, 1):
            base = u * h
            c0 = metric[:, s0] + o0[q, u, 0][None, :] * l0 + o0[q, u, 1][None, :] * l1
            c1 = metric[:, s1] + o1[q, u, 0][None, :] * l0 + o1[q, u, 1][None, :] * l1
            take = c1 > c0
            new[:, base + q] = np.where(take, c1, c0)
            surv[t][:, base + q] = np.where(take, s1, s0).astype(np.uint8)
        metric, new = new, metric
    fin = metric[:, 0].copy()
    info = np.zeros((B, A), np.uint8)
    rows = np.arange(B)
    st = np.zeros(B, np.int64)
    for t in range(T - 1, -1, -1):
        u = (st >> (K - 2)).astype(np.uint8)
        if t < A:
            info[:, t] = u
        st = surv[t][rows, st]
    return info, fin


def viterbi_frame(llr_int, L, cid, pid, perm):
    """One frame, interleaved LLRs in -> (info_hat[L], metric, crc_ok)."""
    _, _, width = CRC[cid]
    A = L + width
    T = A + K_CONSTRAINT - 1
    ncoded = 2 * T
    dep = depuncture(deinterleave(np.asarray(llr_int, np.float64)[None, :], perm),
                     ncoded, pid)
    a_hat, met = viterbi(dep)
    a_hat = a_hat[0]
    return (a_hat[:L].copy(), float(met[0]),
            bool(crc_check(a_hat, cid)) if width else True)


# ---------------------------------------------------------------------------
# brute force: the third side of the small-block cross-check
# ---------------------------------------------------------------------------
def brute_force_ml(llr_int, L, cid, pid, perm, gen=GEN_POLY, K=K_CONSTRAINT):
    """Max of sum_b c_b*llr_b over all 2^L information sequences.

    The metric is evaluated in the INTERLEAVED domain (tx = interleave(puncture(c))
    dotted with the channel LLRs), which is the same sum the decoder maximises
    because a permutation applied to both factors leaves an inner product alone.
    Shares no code with either Viterbi: enumeration + generator-matrix encode + one
    matmul. Ties take the SMALLEST information index (np.argmax returns the first
    maximum), the enumeration analogue of the slot-0 tie-break -- only the
    all-zero-LLR case can reach a tie.
    """
    _, _, width = CRC[cid]
    A = L + width
    ncoded = 2 * (A + K - 1)
    idx = np.arange(1 << L, dtype=np.int64)
    info = np.stack([(idx >> (L - 1 - b)) & 1 for b in range(L)], axis=1).astype(np.uint8)
    tx = conv_encode_batch(info, cid, gen, K)[:, puncture_mask(ncoded, pid)][:, perm]
    with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
        # Apple's Accelerate BLAS (what numpy 2.0.2 binds to on this M4) leaves the
        # x87/FPSR exception bits dirty and numpy 2 reports them as a RuntimeWarning
        # on the matmul that happens to run next, even when every operand is finite
        # and the result is exact. Verified: the same three lines with
        # numpy's own matmul disabled (np.einsum) warn identically on this host and
        # not on an OpenBLAS build. The inputs here are finite by construction
        # (asserted below), so the warning carries no information; the assert does.
        m = tx.astype(np.float64) @ np.asarray(llr_int, np.float64).ravel()
    assert np.all(np.isfinite(m)), "non-finite brute-force metric"
    b = int(np.argmax(m))
    return float(m[b]), info[b].copy()


# ---------------------------------------------------------------------------
# channel: reuse the repo's own QAM mapping and logsumexp LLR (modem_common)
# ---------------------------------------------------------------------------
def qam_llr(tx_bits, M, n0, rng):
    """tx_bits (B, nb) -> interleaved-order LLRs, through ref/modem's conventions.

    nb is padded up to a multiple of m with zeros (padding is appended AFTER the
    interleaver, so it cannot disturb the permutation, and each symbol's LLRs
    depend only on that symbol, so the first nb LLRs are unaffected).
    """
    m = int(round(np.log2(M)))
    pts, lab = mc.constellation(m)
    x = np.atleast_2d(np.asarray(tx_bits, np.uint8))
    B, nb = x.shape
    npad = -(-nb // m) * m - nb
    if npad:
        x = np.concatenate([x, np.zeros((B, npad), np.uint8)], axis=1)
    sym = mc.qam_map(x.reshape(B, -1, m), m)                  # (B, nsym)
    noise = np.sqrt(n0 / 2.0) * (rng.standard_normal(sym.shape)
                                 + 1j * rng.standard_normal(sym.shape))
    z = sym + noise
    llr = mc.soft_llr(z, pts, lab, n0)                        # (B, nsym, m)
    return llr.reshape(B, -1)[:, :nb]


def direct_llr(tx_bits, amp, sigma, rng):
    """BPSK-equivalent soft bits: llr = (2c-1)*amp + N(0, sigma^2).

    amp = 2*Es/N0 in the BPSK normalisation where the coded bit energy is amp/2;
    this path exists so a case can sit at an exact LLR without a constellation in
    the way (and so the all-zero-LLR tie-break case can be written at all).
    """
    x = np.atleast_2d(np.asarray(tx_bits, np.uint8)).astype(np.float64)
    return (2.0 * x - 1.0) * amp + sigma * rng.standard_normal(x.shape)


