def selfcheck():
    chk = np.unpackbits(np.frombuffer(b"123456789", dtype=np.uint8), bitorder="big")
    for poly, width, init, want, name in CRC_CHECK_VALUES:
        got = crc_div(chk, poly, width, init)
        if got != want:
            raise SystemExit("[fec_ref] %s check value 0x%X != published 0x%X"
                             % (name, got, want))
        # the catalogue's `residue` for all three entries is 0: feeding the
        # message followed by its own (xorout-free) CRC back through gives 0.
        res = crc_div(np.concatenate([chk, crc_bits(got ^ 0, width)]),
                      poly, width, init)
        if res != 0:
            raise SystemExit("[fec_ref] %s residue 0x%X != 0" % (name, res))
    print("[fec_ref] CRC check values OK from polynomial division: "
          "CRC-16/XMODEM 0x31C3 (init 0 = the TS 38.212 configuration), "
          "CRC-16/IBM-3740 0x29B1, CRC-24/OPENPGP 0x21CF02; residue 0 for all 3")

    # polynomial hex <-> term list, so a mistyped constant cannot hide
    for cid, terms in ((1, [24, 23, 18, 17, 14, 11, 10, 7, 6, 5, 4, 3, 1, 0]),
                       (2, [16, 12, 5, 0])):
        name, poly, width = CRC[cid]
        got = sorted([width] + [e for e in range(width) if (poly >> e) & 1],
                     reverse=True)
        if got != terms:
            raise SystemExit("[fec_ref] %s: 0x%X expands to %s, TS 38.212 says %s"
                             % (name, poly, got, terms))
    print("[fec_ref] CRC polynomials OK: 0x864CFB and 0x1021 expand to the "
          "TS 38.212 term lists (24 and 16 taps)")

    rng = np.random.default_rng(3)
    for cid in (1, 2):
        width = CRC[cid][2]
        for A in (1, 7, 8, 37, 100, 257):
            msg = rng.integers(0, 2, A).astype(np.uint8)
            cw = crc_append(msg, cid)
            if not crc_check(cw, cid):
                raise SystemExit("[fec_ref] CRC residual != 0 at A=%d cid=%d" % (A, cid))
            mat = crc_matrix(A, CRC[cid][1], width)
            # matrix form vs division form, on a length that is NOT a multiple of 8
            v = int((msg.astype(np.int8) @ mat.T) % 2 @ (1 << np.arange(width - 1, -1, -1)))
            if v != crc_div(msg, CRC[cid][1], width):
                raise SystemExit("[fec_ref] CRC matrix != division at A=%d cid=%d" % (A, cid))
            # recurrence-built matrix vs gf2_mod, every column
            g = CRC[cid][1] | (1 << width)
            for i in range(A):
                col = int(mat[:, i] @ (1 << np.arange(width - 1, -1, -1)))
                if col != gf2_mod(1 << (width + A - 1 - i), g):
                    raise SystemExit("[fec_ref] crc_matrix column %d wrong (A=%d)" % (i, A))
            # a single flipped bit must always be caught
            bad = cw.copy()
            bad[A // 2] ^= 1
            if crc_check(bad, cid):
                raise SystemExit("[fec_ref] CRC missed a single-bit error at A=%d" % A)
    print("[fec_ref] CRC OK: residual 0, matrix == division, recurrence == gf2_mod "
          "on every column, single-bit errors caught (A = 1,7,8,37,100,257)")

    # encoder: generator matrix == XOR of shifted impulse responses (linearity),
    # and the impulse response is what the free-distance search will reproduce.
    G = gen_matrix(24)
    for _ in range(8):
        a = rng.integers(0, 2, 24).astype(np.int8)
        b = rng.integers(0, 2, 24).astype(np.int8)
        u = np.concatenate([a, np.zeros(K_CONSTRAINT - 1, np.int8)])
        v = np.concatenate([b, np.zeros(K_CONSTRAINT - 1, np.int8)])
        if not np.array_equal(((u + v) @ G) % 2, ((u @ G) % 2) ^ ((v @ G) % 2)):
            raise SystemExit("[fec_ref] conv encoder is not linear over GF(2)")
    imp = np.zeros((24 + K_CONSTRAINT - 1, 2 * (24 + K_CONSTRAINT - 1)), np.int8)
    for t in range(24):
        e = np.zeros(24 + K_CONSTRAINT - 1, np.int8)
        e[t] = 1
        imp[t] = (e @ G) % 2
    a = rng.integers(0, 2, 24).astype(np.int8)
    acc = np.zeros(2 * (24 + K_CONSTRAINT - 1), np.int8)
    for t in range(24):
        if a[t]:
            acc ^= imp[t]
    u = np.concatenate([a, np.zeros(K_CONSTRAINT - 1, np.int8)])
    if not np.array_equal(acc, (u @ G) % 2):
        raise SystemExit("[fec_ref] encoder != XOR of shifted impulse responses")
    w1 = int(imp[0].sum())
    print("[fec_ref] conv encoder OK: GF(2)-linear, equals the XOR of shifted "
          "impulse responses; impulse-response weight = %d" % w1)

    # d_free by exhaustive enumeration of every zero-tailed codeword with up to
    # D_FREE_WINDOW information bits. Rigorous for this window; the window
    # contains the optimum because the C++ bounded search attains it at 7
    # branches and the weight-1 input already reaches weight %d (printed above).
    A = D_FREE_WINDOW
    Gx = gen_matrix(A)
    idx = np.arange(1 << A, dtype=np.int64)
    U = np.stack([(idx >> (A - 1 - b)) & 1 for b in range(A)], axis=1).astype(np.int8)
    U = np.concatenate([U, np.zeros((1 << A, K_CONSTRAINT - 1), np.int8)], axis=1)
    W = ((U @ Gx) % 2).sum(axis=1)
    nz = U.any(axis=1)
    d_free = int(W[nz].min())
    if d_free != D_FREE_EXPECTED:
        raise SystemExit("[fec_ref] exhaustive d_free = %d, expected %d"
                         % (d_free, D_FREE_EXPECTED))
    imp_w = [int(W[(U[:, :A].sum(axis=1) == k) & nz].min()) for k in (1, 2, 3)]
    print("[fec_ref] d_free = %d by exhaustive enumeration of all 2^%d zero-tailed "
          "codewords (min output weight at input weight 1/2/3 = %s)"
          % (d_free, A, imp_w))

    for pid, want in ((0, (1, 2)), (1, (2, 3)), (2, (3, 4))):
        got = puncture_rate(pid)
        if got != want:
            raise SystemExit("[fec_ref] puncture pattern %d gives rate %d/%d, want %d/%d"
                             % (pid, got[0], got[1], want[0], want[1]))
    print("[fec_ref] puncture rates OK, counted out of the patterns: 1/2, 2/3, 3/4")

    # interleaver: exact inverse, a real permutation, zero spread violations
    for n in (1, 2, 3, 4, 17, 100, 244, 1000):
        for kind in (0, 1, 2):
            perm, par, att = make_interleaver(kind, n, 8, 20261026)
            if sorted(perm.tolist()) != list(range(n)):
                raise SystemExit("[fec_ref] interleaver kind=%d n=%d not a permutation"
                                 % (kind, n))
            x = rng.integers(0, 256, n).astype(np.uint8)
            if not np.array_equal(deinterleave(interleave(x, perm), perm), x):
                raise SystemExit("[fec_ref] deinterleave(interleave(x)) != x "
                                 "(kind=%d n=%d)" % (kind, n))
            if kind == 2 and par > 0:
                v = spread_violations(perm, par)
                if v != 0:
                    raise SystemExit("[fec_ref] S-random violated: n=%d S=%d %d pairs"
                                     % (n, par, v))
                # min spread > S is the same statement as 0 violations, printed as a
                # number so "how much interleaving did we actually get" is visible
                if min_spread(perm, par) <= par:
                    raise SystemExit("[fec_ref] min_spread %d <= S %d at n=%d"
                                     % (min_spread(perm, par), par, n))
                print("           n=%-5d S_eff=%-2d min spread=%-2d restarts=%d"
                      % (n, par, min_spread(perm, par), att))
    print("[fec_ref] interleavers OK: exact inverses, true permutations, "
          "S-random spread satisfied for n = 4..1000 (S clamped by sqrt(n)/3)")

    # modem conventions against production, if this tree has it
    try:
        mc.check_production()
    except ImportError as e:
        print("[fec_ref] WARNING: production modem cross-check skipped (%s) -- the "
              "QAM/LLR conventions below come from tools/modem_common.py only" % e)
    return d_free


