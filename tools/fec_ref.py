#!/usr/bin/env python3
"""fec_ref: the independent numpy oracle for the FEC layer (ref/fec.cpp).

This is NOT a transcription of the C++ -- the formulations are deliberately
different so that agreement means something:

  quantity          ref/fec.cpp                      this file
  ----------------  -------------------------------  ----------------------------
  CRC               MSB-first LFSR + a 256-entry     GF(2)[x] polynomial division
                    byte table                       (gf2_mod) AND a (width x A)
                                                     GF(2) matrix built from
                                                     x^(w+A-1-i) mod g
  conv encoder      shift register, one branch at a  generator-matrix multiply
                    time                             (U @ G) % 2 over a block
                                                     lower-triangular Toeplitz G
  Viterbi           scalar 64-state loop with a      batched (B, ns, 2) array
                    survivor byte per step           arithmetic, fancy-indexed
  d_free            Dijkstra on the state graph +    exhaustive enumeration of all
                    layered Bellman-Ford             2^16 zero-tailed codewords
  interleaver       greedy S-random + restart ladder THE SAME ALGORITHM (see below)

The interleaver is the one place the two sides must run identical code: the
permutation is a function of (kind, n, par, seed) and the C++ regenerates it from
the seed instead of reading it back, so the permutation itself is a cross-checked
quantity (runtime/fec_main.cpp compares all n entries and the restart count). The
search is inherently sequential -- a rejection sampler whose draw count depends on
its own history -- so numpy vectorises the constraint test but not the walk. The
oracle's independence therefore lives in the trellis, the CRC and the encoder, not
here.

Conventions (shared with ref/fec.h, and gated there):
  * one bit per uint8, trellis state indexing = sionna.phy.fec.conv.Trellis
  * zero-tail termination, n_coded = 2*(A + K - 1)
  * llr > 0 favours bit value 1 (ref/modem.h, tools/modem_common.py)
  * path metric MAXIMISED: sum over coded bits of c_b * llr_b; punctured
    positions carry llr == 0.0 exactly
  * metric tie -> the smaller predecessor state wins (slot 0)

Self-checks run before anything is written out; they are the reason the numbers in
build/fec_vectors.bin can be called ground truth:
  * three externally attested CRC check values for "123456789" are reproduced from
    the polynomial-division form: CRC-16/XMODEM 0x31C3 (init 0 -- the exact
    configuration TS 38.212 uses), CRC-16/IBM-3740 0x29B1 (init 0xFFFF) and
    CRC-24/OPENPGP 0x21CF02 (init 0xB704CE). All three from Greg Cook's
    "Catalogue of parametrised CRC algorithms", class "attested".
  * the residual of a codeword is 0 (TS 38.212 starts the register at zero).
  * the generator-matrix encoder is linear and equals the XOR of shifted impulse
    responses (a second construction of the same linear map).
  * d_free = 10 by exhaustive enumeration, matching the two graph searches in C++.
  * the puncture rate is counted out of the pattern, not typed in.

Writes build/fec_vectors.bin, little endian throughout:
  int32 ncase
  per case (scalars first, then arrays -- the order is the contract with
  runtime/fec_main.cpp):
    int32   L, crc_id, punct_id, int_kind, int_par_req, int_par_eff, int_attempts,
            M, ncoded, npunc, has_bf
    int64   seed
    float64 n0, amp, metric, bf_metric
    uint8   crc_ok
    uint8   info[L]         information bits, before the CRC
    uint8   coded[ncoded]   unpunctured encoder output (CRC'd, zero-tailed)
    uint8   tx[npunc]       punctured AND interleaved bits, what the modem sees
    int32   perm[npunc]     the interleaver permutation, regenerated by the C++
    float64 llr[npunc]      LLRs in interleaved order
    uint8   dec[L]          expected decoded information bits
    uint8   bf_info[L]      brute-force ML bits (zeros when has_bf == 0)
  crc_id: 0 none, 1 CRC-24A, 2 CRC-16.  punct_id: 0 rate 1/2, 1 rate 2/3,
  2 rate 3/4.  int_kind: 0 identity, 1 row-column, 2 s-random.  M = 0 means the
  LLRs were synthesised directly (BPSK-equivalent soft bits) instead of coming out
  of a QAM demodulator.
"""
