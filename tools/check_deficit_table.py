#!/usr/bin/env python3
"""deficit_check: gate for the duplicated ln-deficit lookup table.

The table main.tex:169-171 describes ("log D on a uniform log-gamma grid of 1600
points per modulation and branch, with the analytic tail C*Q(t) beyond it") is
generated by tools/gen_deficit_table.py into TWO files, following the
Gauss-Hermite pattern (gen_gh_table.py / gen_gh_cl.py + check_gh.py):

  include/deficit_table.h    fp64, consumed by ref/threshold_cf.cpp   (PS path)
  kernels/deficit_table.clh  fp64 + fp32 blocks, consumed by
                             kernels/threshold_cf.cl                  (PL path)

Nothing in the build would notice if the two drifted, or if a committed table
were stale with respect to its own generator, or if a row were transposed (fin
and mod differ by exactly the Lemma-4 factor L/(L-1) at high SNR, so a swap is
a 0.5-1.2 dB error in the deficit -- far too small to trip cf_bench's fp32
tolerance of 5e-2 dB, and invisible to a quadrature-vs-quadrature gate). This
script is that comparison. Checks, in order of severity:

  1. grid parameters (DFT_N / DFT_NM / DFT_ROWS / DFT_TLO / DFT_THI / DFT_LNTLO
     / DFT_DLNT / DFT_DLNG) identical in both files, and DFT_DLNG == 2*DFT_DLNT
     (the ln-gamma / ln-t identity the paper's "log-gamma grid" rests on).
  2. kDFT_M identical, every entry a perfect square with 5*ceil(L/2) <= 128
     (the MAXD capacity of kernels/threshold_cf.cl) and L a power of two.
  3. fp64 kDFT_LND bit-identical between the two files.
  4. the fp32 block in the device header is the correctly-rounded narrowing of
     the fp64 block, to within 1 ulp (the generator emits %.9e).
  5. structural properties of the committed numbers, i.e. that they are a
     deficit table and not just two equal files:
       a. ln D strictly decreasing in t along every row (D is a decreasing
          function of SNR -- a single transposed or repeated value fails this);
       b. the t -> 0 limit: |D(t_0)/log2(M) - 1| <= 800*t_0^2, the measured
          1 - c*t^2 law (c = 721 for L = 2, 385 for L = 8, 115 for L = 16 ...
          all < 800), which also pins the row to the right constellation:
          log2(M) is different for every M in the table;
       c. Lemma 4: D_mod/D_fin == L/(L-1) to 1e-12 relative for every grid
          t >= 5 (measured worst 5.5e-14, M = 4; the ratio drifts below
          t = 2.3..3.7 depending on M, which is the model and not the table).
          This is the check that catches a fin/mod row swap and a wrong-M row;
       d. the tail handover: |ln D(t_hi) - (ln C + lnQ_asym(t_hi))| <= 0.006 dB.
          This is the step the deployed function takes when it leaves the grid;
          the value it replaces (the quadrature->tail switch at TQ = 5) is
          0.3046 dB, and the bound is the measured 0.00521 dB with 15% margin;
       e. no single corrupted entry: every 4th finite difference is within 8x of
          the local 41-point median of |d4|. A corrupted value shows up as five
          consecutive 4th differences of its own size, which no local median can
          absorb; a global median cannot be used because |d4| legitimately
          spans six orders along a row (it grows like t^2 h^4).
  6. INDEPENDENT recomputation at a sparse probe set -- the analogue of
     check_gh.py's check 5 (numpy.hermgauss). Checks 1-5 are all
     self-consistency: two files written by the same wrong generator, or by a
     right generator at the wrong grid, pass every one of them. Here the probes
     are recomputed from scratch with the converged composite-Gauss-Legendre
     reference in tools/gen_deficit_table.py (a different algorithm from the
     GH-48 rule, a different node set, a different weight function) and, at
     t <= 2 where GH-48 is itself good to 6e-5 dB, ALSO compared against that
     live GH-48 rule, which is a fourth independent implementation of the same
     integral (ref/threshold_cf.cpp, kernels/threshold_cf.cl, tools/cf_ref.py).

`--full` regenerates the whole grid into a temporary directory and compares the
two committed files byte-for-byte; that is the check to run before committing a
grid change (~4 min of CPU, parallel with --jobs). The default mode runs the
sparse version of the same thing: a subset of grid columns regenerated and
compared value-for-value, so `make deficit_check` stays inside a few seconds.
"""
from __future__ import annotations

import argparse
import math
import re
import struct
import sys
import tempfile
import pathlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
HOST = ROOT / "include" / "deficit_table.h"
DEVICE = ROOT / "kernels" / "deficit_table.clh"
sys.path.insert(0, str(ROOT / "tools"))

FP32_ULP_TOL = 1.0        # check 4: fp32 narrowing, in ulps (as in check_gh.py)
RECOMPUTE_TOL = 1e-9      # check 6: nats of ln D (4.3e-9 dB)
GH_PROBE_T = (0.5, 1.0, 1.5, 2.0)     # where GH-48 is good to <= 6e-5 dB
GH_TOL_DB = 2e-3                      # measured worst over those probes: 5.8e-5
# Lemma-4 probe range and tolerance, measured on the committed grid: the ratio
# D_mod/D_fin equals L/(L-1) to 5.5e-14 (M=4), 5.1e-14 (16), 3.2e-14 (64),
# 3.6e-14 (256), 2.1e-14 (1024) for every grid t >= 5, and it is only below
# t = 3.67 / 2.43 / 2.38 / 2.34 / 2.28 respectively that the model's own
# low-SNR behaviour lets the ratio drift (6.9e-7 at t = 3 for M = 4). tools/
# cf_ref.py probes t = 3.5 with a 1e-9 tolerance on the QUADRATURE, which is
# inside that drift region for M = 4 and outside it for M >= 16 -- the reason its
# probe set starts at M = 16. 1e-12 leaves 2.5 orders of margin over the worst
# measured row and still fails on a fin/mod row swap (56%), a wrong-M row, a
# transposed table or a broken interpolator.
LEMMA4_TMIN = 5.0
LEMMA4_TOL = 1e-12
HANDOVER_TOL_DB = 6e-3                # measured 5.21e-3 dB at DFT_THI = 32
SAT_C = 800.0                         # check 5b: |D/log2M - 1| <= C * t0^2
SPARSE_STRIDE = 200                   # default regenerate-and-compare columns
DFT_TMONO = 1.0                       # check 5a: strictly decreasing above this t
MONO_BUMP = 2.5e-2                    # check 5a: nats of total rise allowed below it
SPIKE_TOL = 8.0                       # check 5e: |d4| / local 41-point median


def fail(msg: str) -> None:
    print(f"[deficit_check] FAIL: {msg}")
    sys.exit(1)


def read(path: pathlib.Path) -> str:
    if not path.is_file():
        fail(f"missing {path} (run: python3 tools/gen_deficit_table.py)")
    return path.read_text()


def define(text: str, name: str, path: pathlib.Path, cast=float):
    m = re.search(r"#define\s+" + name + r"\s+([-+0-9.eE()*/ ]+)", text)
    if not m:
        fail(f"{path.name}: no '#define {name}'")
    return cast(eval(m.group(1), {"__builtins__": {}})) if cast is not int else \
        int(cast(eval(m.group(1), {"__builtins__": {}})))


def _num(tok: str) -> float:
    """A table literal. The fp32 block carries an `f` suffix (see the generator:
    an unsuffixed 9-digit literal is a DOUBLE constant in OpenCL C and the PL
    build warns once per value), which float() does not accept."""
    return float(tok.rstrip("fF"))


def blocks(text: str, name: str):
    """Every `name[..][..] = { ... };` initializer, in file order, as a list of
    rows of floats. The device header carries two (fp64 then fp32), the host
    header one -- the same shape as check_gh.py's blocks()."""
    out = []
    for m in re.finditer(re.escape(name) + r"\s*\[[^\]]*\]\s*\[[^\]]*\]\s*=\s*\{",
                         text):
        i, depth, start, rows = m.end() - 1, 0, None, []
        while i < len(text):
            ch = text[i]
            if ch == "{":
                depth += 1
                if depth == 2:
                    start = i + 1
            elif ch == "}":
                depth -= 1
                if depth == 1 and start is not None:
                    chunk = re.sub(r"/\*.*?\*/", " ", text[start:i], flags=re.S)
                    rows.append([_num(t) for t in chunk.replace("\n", " ").split(",")
                                 if t.strip()])
                    start = None
                if depth == 0:
                    break
            i += 1
        out.append(rows)
    return out


def bits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def fp32_ulp_distance(got: float, want: float) -> float:
    g = struct.unpack("<I", struct.pack("<f", got))[0]
    w = struct.unpack("<I", struct.pack("<f", want))[0]
    return float(abs(int(g) - int(w)))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--full", action="store_true",
                    help="regenerate the whole grid and compare both files byte-for-byte")
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--no-recompute", action="store_true",
                    help="skip check 6 (the sparse quadrature recomputation)")
    a = ap.parse_args(argv)

    import gen_deficit_table as G

    host, device = read(HOST), read(DEVICE)

    # ---- 1. grid parameters ------------------------------------------------
    P = {}
    for name, cast in (("DFT_N", int), ("DFT_NM", int), ("DFT_ROWS", int),
                       ("DFT_TLO", float), ("DFT_THI", float), ("DFT_LNTLO", float),
                       ("DFT_DLNT", float), ("DFT_DLNG", float)):
        hv, dv = define(host, name, HOST, cast), define(device, name, DEVICE, cast)
        if bits(float(hv)) != bits(float(dv)):
            fail(f"{name} differs: {HOST.name}={hv!r} vs {DEVICE.name}={dv!r} "
                 f"-- host and device would interpolate on different grids")
        P[name] = hv
    n, nm, rows = P["DFT_N"], P["DFT_NM"], P["DFT_ROWS"]
    if rows != 2 * nm:
        fail(f"DFT_ROWS = {rows} but 2*DFT_NM = {2*nm}")
    if abs(P["DFT_DLNG"] - 2 * P["DFT_DLNT"]) > 1e-15 * abs(P["DFT_DLNG"]):
        fail("DFT_DLNG != 2*DFT_DLNT: the ln-gamma grid is not the ln-t grid")
    want_h = math.log(P["DFT_THI"] / P["DFT_TLO"]) / (n - 1)
    if abs(P["DFT_DLNT"] - want_h) > 1e-14 * want_h:
        fail(f"DFT_DLNT = {P['DFT_DLNT']:.17e} but ln(THI/TLO)/(N-1) = {want_h:.17e}")
    if abs(P["DFT_LNTLO"] - math.log(P["DFT_TLO"])) > 1e-15 * abs(P["DFT_LNTLO"]):
        fail("DFT_LNTLO != ln(DFT_TLO)")
    print(f"[deficit_check] grid: N={n} rows={rows} (M x 2 branches) "
          f"t=[{P['DFT_TLO']:g},{P['DFT_THI']:g}] h(ln t)={P['DFT_DLNT']:.6e} "
          f"h(ln gamma)={P['DFT_DLNG']:.6e}")

    # ---- 2. constellation list --------------------------------------------
    mh = re.search(r"kDFT_M\[DFT_NM\]\s*=\s*\{([^}]*)\}", host)
    md = re.search(r"kDFT_M\[DFT_NM\]\s*=\s*\{([^}]*)\}", device)
    if not mh or not md:
        fail("kDFT_M not found in one of the two headers")
    Ms = [int(x) for x in mh.group(1).replace("\n", " ").split(",") if x.strip()]
    Ms_d = [int(x) for x in md.group(1).replace("\n", " ").split(",") if x.strip()]
    if Ms != Ms_d:
        fail(f"kDFT_M differs: {Ms} vs {Ms_d}")
    if len(Ms) != nm:
        fail(f"kDFT_M has {len(Ms)} entries but DFT_NM = {nm}")
    for M in Ms:
        L = int(round(math.sqrt(M)))
        if L * L != M or L < 2 or (L & (L - 1)):
            fail(f"kDFT_M entry {M} is not a power-of-four constellation (L={L})")
        if 5 * ((L + 1) // 2) > 128:
            fail(f"kDFT_M entry {M} exceeds the MAXD = 128 folded capacity")
    print(f"[deficit_check] constellations: {Ms} (all square, power-of-two L, MAXD-legal)")

    # ---- 3/4. the two tables ---------------------------------------------
    hb, db = blocks(host, "kDFT_LND"), blocks(device, "kDFT_LND")
    if len(hb) != 1:
        fail(f"{HOST.name}: expected 1 kDFT_LND block, found {len(hb)}")
    if len(db) != 2:
        fail(f"{DEVICE.name}: expected 2 kDFT_LND blocks (fp64 + fp32), found {len(db)}")
    h64, d64, d32 = hb[0], db[0], db[1]
    for tag, arr in ((f"{HOST.name}", h64), (f"{DEVICE.name} fp64", d64),
                     (f"{DEVICE.name} fp32", d32)):
        if len(arr) != rows:
            fail(f"{tag}: {len(arr)} rows but DFT_ROWS = {rows}")
    for tag, arr in ((f"{HOST.name}", h64), (f"{DEVICE.name} fp64", d64),
                     (f"{DEVICE.name} fp32", d32)):
        for r, v in enumerate(arr):
            if len(v) != n:
                fail(f"{tag} row {r}: {len(v)} values but DFT_N = {n}")
    nbad = 0
    for r in range(rows):
        for k in range(n):
            if bits(h64[r][k]) != bits(d64[r][k]):
                nbad += 1
                if nbad == 1:
                    fail(f"kDFT_LND[{r}][{k}] fp64 differs: host={h64[r][k]!r} "
                         f"device={d64[r][k]!r}")
    print(f"[deficit_check] fp64 table: {rows}x{n} = {rows*n} values bit-identical "
          f"in both headers")
    worst = 0.0
    for r in range(rows):
        for k in range(n):
            worst = max(worst, fp32_ulp_distance(d32[r][k], d64[r][k]))
    if worst > FP32_ULP_TOL:
        fail(f"fp32 block is {worst} ulps from the fp64 narrowing (tol {FP32_ULP_TOL})")
    print(f"[deficit_check] fp32 block: correctly-rounded narrowing, worst {worst:.0f} ulp")

    T = np.exp(P["DFT_LNTLO"] + P["DFT_DLNT"] * np.arange(n))
    A = np.array(h64)                                  # [rows, n] of ln D

    # ---- 5a. monotone decreasing above TMONO, bounded bump below ---------
    # main.tex:140 says "each deficit is positive and decreasing". That is true
    # of the unfolded (fin) axis everywhere and of the folded (mod) axis only
    # above t ~ 0.6/L. Below it the folded deficit dips and comes back up once:
    # measured on the committed grid, the rise is confined to
    #     M=4 t in [0.224,0.531]  M=16 [0.112,0.267]  M=64 [0.056,0.135]
    #     M=256 [0.028,0.067]     M=1024 [0.014,0.034]
    # and totals 1.67e-2 nats (0.073 dB) at M=4 down to 3.3e-3 nats (0.015 dB)
    # at M=1024, with a largest single grid step of 2.6e-4 nats. It is a
    # property of the MODEL, not of this table: the live GH-48 rule reproduces
    # the same rise to 2.5e-5 nats (checked below at t <= 2), because the modulo
    # images make the folded LLR briefly less damaging than the label entropy
    # baseline before the error-event term takes over. So the check is split:
    # strictly decreasing for t >= DFT_TMONO, and below it no rise at all on the
    # fin rows and at most MONO_BUMP nats of total rise on the mod rows.
    dA = np.diff(A, axis=1)
    kmono = int(np.searchsorted(T, DFT_TMONO))
    if not np.all(dA[:, kmono - 1:] < 0.0):
        r, k = np.unravel_index(np.argmax(dA[:, kmono - 1:] >= 0.0),
                                dA[:, kmono - 1:].shape)
        fail(f"row {r} (M={Ms[r//2]} {'mod' if r % 2 else 'fin'}) is not strictly "
             f"decreasing at t={T[kmono+k]:.4f} >= {DFT_TMONO:g}: "
             f"{A[r][kmono+k]:.17e} -> {A[r][kmono+k+1]:.17e}")
    rise = np.where(dA > 0.0, dA, 0.0).sum(axis=1)
    for r in range(rows):
        if r % 2 == 0 and rise[r] > 0.0:
            fail(f"row {r} (M={Ms[r//2]} fin) rises by {rise[r]:.3e} nats below "
                 f"t={DFT_TMONO:g}; the unfolded axis is monotone everywhere")
        if rise[r] > MONO_BUMP:
            fail(f"row {r} (M={Ms[r//2]} mod) rises by {rise[r]:.3e} nats, over the "
                 f"{MONO_BUMP:g} nat bound for the folded low-t bump")
        if np.any(dA[r] > 0.0) and T[int(np.argmax(dA[r] > 0.0))] > DFT_TMONO:
            fail(f"row {r}: a rising step above t={DFT_TMONO:g}")
    print(f"[deficit_check] monotone: strictly decreasing for t >= {DFT_TMONO:g} "
          f"(steepest step {dA[:, kmono-1:].max():.3e} nats); below it the fin rows "
          f"never rise and the mod rows rise by <= {rise.max():.2e} nats total "
          f"({4.343*rise.max():.2e} dB, the folded low-t bump, reproduced by GH-48)")

    # ---- 5b. the t -> 0 limit is log2(M) ---------------------------------
    t0 = T[0]
    for r in range(rows):
        M = Ms[r // 2]
        rel = math.exp(A[r][0]) / math.log2(M) - 1.0
        if not (-SAT_C * t0 * t0 <= rel <= 0.0):
            fail(f"row {r} (M={M}): D(t0={t0:g})/log2(M) - 1 = {rel:.3e}, outside "
                 f"[-{SAT_C*t0*t0:.1e}, 0] -- wrong constellation or wrong branch")
    print(f"[deficit_check] low-t limit: D({T[0]:g}) == log2(M)*(1 - c*t^2), "
          f"worst relative deviation "
          f"{max(abs(math.exp(A[r][0])/math.log2(Ms[r//2]) - 1) for r in range(rows)):.2e}")

    # ---- 5c. Lemma 4 ratio over the whole high-SNR half of the grid -------
    worst4, worst4_t = 0.0, 0.0
    kmin = int(np.searchsorted(T, LEMMA4_TMIN))
    for mi, M in enumerate(Ms):
        L = int(round(math.sqrt(M)))
        fin, mod = A[2 * mi], A[2 * mi + 1]
        rel = np.abs(np.exp(mod[kmin:] - fin[kmin:]) - L / (L - 1.0)) / (L / (L - 1.0))
        i = int(np.argmax(rel))
        if rel[i] > worst4:
            worst4, worst4_t = float(rel[i]), float(T[kmin:][i])
        if rel[i] > LEMMA4_TOL:
            fail(f"M={M}: Lemma-4 ratio D_mod/D_fin = {math.exp(mod[kmin:][i]-fin[kmin:][i]):.12f} "
                 f"at t={T[kmin:][i]:.4f}, expected L/(L-1) = {L/(L-1):.12f} "
                 f"(rel err {rel[i]:.2e} > {LEMMA4_TOL:g})")
    print(f"[deficit_check] Lemma 4: D_mod/D_fin == L/(L-1) for all t >= {LEMMA4_TMIN:g} "
          f"({n-kmin} grid points x {len(Ms)} M), worst rel err {worst4:.2e} at t={worst4_t:.3f}")

    # ---- 5d. tail handover step ------------------------------------------
    worst_step = 0.0
    for r in range(rows):
        M, folded = Ms[r // 2], bool(r % 2)
        L = int(round(math.sqrt(M)))
        tail = math.log(G.c_const(folded, L)) + float(G.lnQ_asym(T[-1]))
        step = abs(4.342944819 * (A[r][-1] - tail))
        worst_step = max(worst_step, step)
        if step > HANDOVER_TOL_DB:
            fail(f"row {r} (M={M}): handover step at t={T[-1]:g} is {step:.5f} dB "
                 f"> {HANDOVER_TOL_DB:g} dB")
    print(f"[deficit_check] tail handover at t={T[-1]:g}: {worst_step:.5f} dB step "
          f"(the TQ=5 quadrature->tail switch it replaces is 0.3046 dB)")

    # ---- 5e. no single corrupted entry -----------------------------------
    # A corrupted value at k0 shows up as five consecutive 4th differences of
    # magnitude ~|corruption| with alternating sign. A GLOBAL median is useless
    # as the scale here: |d4| of ln D grows like t^2*h^4 along the row, so it
    # spans six orders between the flat low-t end and t = DFT_THI (3.1e-5 at
    # k = 1595 against a row median of 1.4e-10 -- which is exactly why the first
    # version of this check failed on a correct table). The scale is therefore a
    # LOCAL median over a 41-point window, and the test is skipped where the 4th
    # difference is below the fp64 round-off of the row values themselves.
    d4 = np.abs(np.diff(A, n=4, axis=1))
    win = np.lib.stride_tricks.sliding_window_view(d4, 41, axis=1)
    # edge-replicate, NOT zero-pad: the last 20 columns have no centred window,
    # and a zero scale there turns the smooth top-of-grid growth of |d4| into an
    # infinite "spike" (that is how the first version of this check failed).
    loc = np.pad(np.median(win, axis=2), ((0, 0), (20, 20)), mode="edge")
    floor = 1e-11 * d4.max(axis=1, keepdims=True)
    ratio = np.where(d4 > np.maximum(floor, 1e-300), d4 / np.maximum(loc, 1e-300), 0.0)
    worst = float(ratio.max())
    if worst > SPIKE_TOL:
        r, k = np.unravel_index(int(np.argmax(ratio)), ratio.shape)
        fail(f"row {r} (M={Ms[r//2]}) has a 4th-difference spike at k={k} "
             f"(t={T[k+2]:.4g}): {d4[r][k]:.3e} against a local median of "
             f"{loc[r][k]:.3e}, ratio {worst:.1f} > {SPIKE_TOL:g} -- corrupted entry?")
    print(f"[deficit_check] 4th-difference smoothness: worst local spike ratio "
          f"{worst:.2f} (tol {SPIKE_TOL:g}); |d4| spans "
          f"{d4[d4>0].min():.1e}..{d4.max():.1e} nats along a row")

    # ---- 6. independent recomputation + regenerate-and-compare ----------
    if a.no_recompute:
        print("[deficit_check] check 6 skipped (--no-recompute)")
    else:
        cols = list(range(0, n, SPARSE_STRIDE)) + [n - 1]
        cols = sorted(set(cols))
        probes = [(r, k) for r in range(rows) for k in cols]
        pool = None
        if a.jobs > 1:
            from multiprocessing import Pool
            pool = Pool(a.jobs)
        jobs = [(float(T[k]), Ms[r // 2], bool(r % 2), 1.0, 8, 1.0)
                for r, k in probes]
        vals = np.array(pool.map(G._one, jobs, chunksize=4)) if pool else \
            np.array([G._one(j) for j in jobs])
        if pool:
            pool.close(); pool.join()
        worst = 0.0
        at = None
        for (r, k), v in zip(probes, vals):
            e = abs(v - A[r][k])
            if e > worst:
                worst, at = float(e), (r, k)
        if worst > RECOMPUTE_TOL:
            r, k = at
            fail(f"regenerated ln D[{r}][{k}] (M={Ms[r//2]}, "
                 f"{'mod' if r%2 else 'fin'}, t={T[k]:.6g}) = {v:.15e} but the "
                 f"committed table says {A[r][k]:.15e} ({worst:.3e} nats > "
                 f"{RECOMPUTE_TOL:g}): the committed table is stale or was "
                 f"generated from a different model")
        print(f"[deficit_check] regenerated {len(probes)} grid values "
              f"({len(cols)} of {n} columns x {rows} rows): worst |diff| = "
              f"{worst:.2e} nats = {4.343*worst:.2e} dB (tol {RECOMPUTE_TOL:g} nats)")

        # ... and against the LIVE GH-48 rule, an independent implementation of
        # the same integral that is itself trustworthy at these t.
        wq, wq_at = 0.0, None
        for r in range(rows):
            M, folded = Ms[r // 2], bool(r % 2)
            L = int(round(math.sqrt(M)))
            for t in GH_PROBE_T:
                ln_gh = math.log(2.0 * G.axis_gh(t, L, folded, 48))
                # Compare the DEPLOYED evaluation -- table + 4-point Lagrange at
                # exactly this t, not at the nearest node -- against GH-48, so the
                # number carries the interpolation error and GH-48's own error at
                # that t and nothing else. (An earlier version read the nearest
                # grid node instead, which added the half-step offset of ln D and
                # reported 4.0e-2 dB of "error" that was the probe, not the table.)
                ln_tab = float(G.interp_ln_deficit(A[r], t, n, P["DFT_TLO"], P["DFT_THI"]))
                e = abs(4.342944819 * (ln_gh - ln_tab))
                if e > wq:
                    wq, wq_at = e, (M, folded, t)
        if wq > GH_TOL_DB:
            M, folded, t = wq_at
            fail(f"table vs live GH-48 quadrature: {wq:.3e} dB > {GH_TOL_DB:g} dB at "
                 f"M={M} {'mod' if folded else 'fin'} t={t:g}")
        print(f"[deficit_check] table + Lagrange vs the live GH-48 rule at "
              f"t = {GH_PROBE_T}, all {rows} rows: worst {wq:.2e} dB "
              f"(M={wq_at[0]} {'mod' if wq_at[1] else 'fin'} t={wq_at[2]:g}); GH-48's "
              f"own error there is <= 1.1e-4 dB, so this is agreement, not accuracy")

    if a.full:
        with tempfile.TemporaryDirectory() as td:
            h2 = pathlib.Path(td) / "deficit_table.h"
            d2 = pathlib.Path(td) / "deficit_table.clh"
            G.main(["--jobs", str(a.jobs), "--host", str(h2), "--device", str(d2),
                    "--quiet"])
            for want, got in ((h2, HOST), (d2, DEVICE)):
                if want.read_bytes() != got.read_bytes():
                    fail(f"{got} is NOT byte-identical to a fresh regeneration "
                         f"({want}): edit the generator, never the header")
                print(f"[deficit_check] full regenerate-and-compare: {got.name} "
                      f"byte-identical ({got.stat().st_size/1024:.0f} KB)")

    kb = rows * n
    print(f"[deficit_check] OK: {rows} rows x {n} points, "
          f"PL footprint fp32 {kb*4/1024:.1f} KB / fp64 {kb*8/1024:.1f} KB, "
          f"host fp64 {kb*8/1024:.1f} KB")
    return 0


