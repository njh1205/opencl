#!/usr/bin/env python3
"""Emit the OpenCL-side Gauss-Hermite table (kernels/gh_table.clh)."""
import numpy as np, pathlib
N = 48
z, w = np.polynomial.hermite.hermgauss(N)
# The fp64 extension pragma MUST precede the first `double` in the translation
# unit. threshold_cf.cl includes this header before its own pragma block, so a
# strict OpenCL C front-end rejected the `__constant double` arrays below with
# "requires cl_khr_fp64" (Apple's ICD enables fp64 by default, which is why this
# never surfaced on the dev host). Emitting the pragma here keeps the header
# self-sufficient. The include guard matters because Runtime::build() inlines
# #include textually and concatenates every .cl into one program source.
lines = ["// auto-generated by tools/gen_gh_cl.py (do not edit)",
         "#ifndef HPOCL_GH_TABLE_CLH",
         "#define HPOCL_GH_TABLE_CLH",
         "#define GH_N %d" % N,
         "#ifndef HPOCL_FP32",
         "#pragma OPENCL EXTENSION cl_khr_fp64 : enable",
         "__constant double kGH_Z[GH_N] = {"]
lines += [", ".join("%.17e" % v for v in z[i:i+4]) + "," for i in range(0, N, 4)]
lines += ["};", "__constant double kGH_W[GH_N] = {"]
lines += [", ".join("%.17e" % v for v in w[i:i+4]) + "," for i in range(0, N, 4)]
lines += ["};",
          "#else",
          "__constant float kGH_Z[GH_N] = {"]
lines += [", ".join("%.9e" % v for v in z[i:i+4]) + "," for i in range(0, N, 4)]
lines += ["};", "__constant float kGH_W[GH_N] = {"]
lines += [", ".join("%.9e" % v for v in w[i:i+4]) + "," for i in range(0, N, 4)]
lines += ["};", "#endif", "#endif  // HPOCL_GH_TABLE_CLH"]
pathlib.Path("kernels/gh_table.clh").write_text("\n".join(lines) + "\n")
print("wrote kernels/gh_table.clh")
