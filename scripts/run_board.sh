#!/usr/bin/env bash
# On-board (Zynq PS) run of the WHOLE device surface, via XRT on the PL.
#
#   scp -r hpocl/ root@<ps-ip>:; ssh root@<ps-ip>
#   cd hpocl && scripts/run_board.sh /lib/firmware/hpocl.xclbin
#
# Why every bench and not three: this script used to run cf_bench/op_bench/
# tf_bench only, which exercised 12 of the 29 kernels -- so decomp, the whole
# per-symbol datapath, the MCS layer, the end-to-end chain and the device-side
# scheduling instant (sched_bench) would have reached the board untested, and a
# kernel that fails to be acquired from an xclbin fails SILENTLY unless something
# asks for it by name (that is exactly how the eight datapath kernels were once
# source-JIT-only and therefore undeployable; see tools/check_registry.py).
#
# Order matters: allprog_check runs FIRST because it is the pre-flight. It builds
# every source as one program and reports the two device limits this library
# actually pushes -- CL_DEVICE_MAX_CONSTANT_BUFFER_SIZE against the 62.5 KB
# deficit table (97.7% of the 64 KB spec minimum, so a minimal device refuses the
# build outright; the fix is a smaller table, printed by the gate itself) and
# CL_DEVICE_LOCAL_MEM_SIZE against wbb_apply's PL tile. If that fails, nothing
# below is worth running.
#
# Vector files: the benches read build/*.bin, which are GENERATED by numpy
# oracles (tools/*_ref.py) and need numpy+scipy+the production python in
# mix_precode/. Generate them on a host that has those (`make cf_ref` etc., or
# just `make check`) and scp build/*.bin along with the tree; this script does
# not try to regenerate them and says so if one is missing.
set -uo pipefail
XCLBIN=${1:?xclbin path on PS}
DEV=${2:-acc}                      # acc = CL_DEVICE_TYPE_ACCELERATOR (the PL)
ROOT=$(cd "$(dirname "$0")/.." && pwd)
export HPOCL_XCLBIN="$XCLBIN"
cd "$ROOT"

# No HPOCL_FP32 export: it never did anything at RUNTIME. Precision is a
# COMPILE-time choice (-DHPOCL_FP32 / -DHPOCL_FP64 to v++ or to the JIT), and
# threshold_cf.cl is fp32 by default, so an xclbin built by build_xclbin.sh is
# the fp32 datapath whether or not this variable is set. Exporting it here used
# to imply otherwise.

fail=0
need() {  # need <file> <generator>
  if [ ! -f "$1" ]; then
    echo "[board] MISSING $1 -- generate it on a host with numpy/scipy: $2"
    fail=1
  fi
}

echo "=== pre-flight: whole library as one program, device limits ==="
./build/allprog_check "$DEV" || { echo "[board] PRE-FLIGHT FAILED -- stop"; exit 1; }

echo; echo "=== control plane ==="
need build/cf_vectors.bin "python3 tools/cf_ref.py"
./build/cf_bench build/cf_vectors.bin "$DEV" || fail=1
./build/op_bench "$DEV" || fail=1
HPOCL_CLOPTS=-DWBB_LOCAL_MAX=4096 ./build/op_bench "$DEV" || fail=1   # the PL tile

echo; echo "=== per-user decompositions ==="
need build/decomp_vectors.bin "python3 tools/decomp_ref.py"
./build/decomp_bench build/decomp_vectors.bin "$DEV" || fail=1

echo; echo "=== device-side scheduling instant (PS role vs PL role) ==="
./build/sched_bench "$DEV" || fail=1

echo; echo "=== per-symbol datapath + code rate ==="
need build/datapath_vectors.bin "python3 tools/datapath_ref.py"
need build/rate_vectors.bin "python3 tools/rate_ref.py"
need build/chain_vectors.bin "python3 tools/chain_ref.py"
./build/datapath_bench build/datapath_vectors.bin "$DEV" || fail=1
HPOCL_CLOPTS=-DLLR_CACHE_MAX=4 ./build/datapath_bench build/datapath_vectors.bin "$DEV" || fail=1
./build/rate_bench build/rate_vectors.bin "$DEV" || fail=1
./build/chain_bench build/chain_vectors.bin "$DEV" || fail=1

echo; echo "=== transformer predictor (skips itself if the checkpoint is absent) ==="
need build/tf_weights.bin "python3 tools/make_random_tf_weights.py"
./build/tf_bench build/tf_weights.bin "$DEV" || fail=1
python3 tools/tf_export_check.py || echo "[board] tf_export_check skipped (no checkpoint / no torch)"

echo
if [ "$fail" -ne 0 ]; then echo "[board] FAILURES above"; exit 1; fi
echo "[board] all device benches passed on $DEV with $XCLBIN"
